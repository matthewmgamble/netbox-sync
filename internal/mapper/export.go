package mapper

import (
	"bytes"
	"fmt"
	"net/http"
	"os"

	"gopkg.in/yaml.v3"
)

func (s *Server) handleExport(w http.ResponseWriter, r *http.Request) {
	s.mu.RLock()
	defer s.mu.RUnlock()

	output, err := s.buildExportYAML()
	if err != nil {
		http.Error(w, "Failed to generate YAML: "+err.Error(), http.StatusInternalServerError)
		return
	}

	w.Header().Set("Content-Type", "application/x-yaml")
	w.Header().Set("Content-Disposition", "attachment; filename=mapping.yaml")
	w.Write(output)
}

// buildExportYAML merges the current mappings into the original mapping file.
// It preserves all existing sections and only replaces the sites section.
func (s *Server) buildExportYAML() ([]byte, error) {
	// Start with the original file content as a generic map to preserve structure
	var rawMap map[string]interface{}

	if s.mappingPath != "" {
		data, err := os.ReadFile(s.mappingPath)
		if err == nil {
			if err := yaml.Unmarshal(data, &rawMap); err != nil {
				rawMap = nil
			}
		}
	}
	if rawMap == nil {
		rawMap = make(map[string]interface{})
	}

	// Build the sites section from current mappings
	sites := make(map[string]interface{})
	for mistID, row := range s.mappings {
		if row.NetBoxSite == "" && row.Region == "" && row.SiteGroup == "" && row.Status == "" {
			continue // skip empty mappings
		}
		entry := make(map[string]interface{})
		if row.NetBoxSite != "" {
			entry["netbox_site_name"] = row.NetBoxSite
		}
		if row.Region != "" {
			entry["region"] = row.Region
		}
		if row.SiteGroup != "" {
			entry["site_group"] = row.SiteGroup
		}
		if row.Status != "" {
			entry["status"] = row.Status
		}
		sites[mistID] = entry
	}

	rawMap["sites"] = sites

	var buf bytes.Buffer
	buf.WriteString("# Site Mapping Configuration\n")
	buf.WriteString(fmt.Sprintf("# Generated by mapper — %d site mappings\n\n", len(sites)))

	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(rawMap); err != nil {
		return nil, err
	}
	enc.Close()

	return buf.Bytes(), nil
}
